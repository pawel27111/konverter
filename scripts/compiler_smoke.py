"""Real CPU export fixture. Run with the installed engine's Python on Linux x64.

Random tiny weights test the export pipeline, not image quality or Apple inference.
"""
import argparse
import json
from pathlib import Path


def create_fixture(folder):
    import torch
    from diffusers import AutoencoderKL, PNDMScheduler, StableDiffusionPipeline, UNet2DConditionModel
    from transformers import CLIPTextConfig, CLIPTextModel, CLIPTokenizer
    torch.manual_seed(123)
    folder.mkdir(parents=True, exist_ok=True)
    token_dir = folder / "tokenizer"
    token_dir.mkdir(exist_ok=True)
    vocab = {"<|startoftext|>": 0, "!": 1, "<|endoftext|>": 2}
    for ch in "abcdefghijklmnopqrstuvwxyz":
        vocab[ch] = len(vocab)
        vocab[ch + "</w>"] = len(vocab)
    (token_dir / "vocab.json").write_text(json.dumps(vocab))
    (token_dir / "merges.txt").write_text("#version: 0.2\n")
    tokenizer = CLIPTokenizer(str(token_dir / "vocab.json"), str(token_dir / "merges.txt"), model_max_length=77)
    text_encoder = CLIPTextModel(CLIPTextConfig(vocab_size=len(vocab), hidden_size=768,
        intermediate_size=768, num_hidden_layers=1, num_attention_heads=12, max_position_embeddings=77,
        bos_token_id=0, eos_token_id=2, pad_token_id=2))
    unet = UNet2DConditionModel(sample_size=64, in_channels=4, out_channels=4, cross_attention_dim=768,
        block_out_channels=(32, 32), layers_per_block=1, norm_num_groups=8, attention_head_dim=8,
        down_block_types=("DownBlock2D", "CrossAttnDownBlock2D"), up_block_types=("CrossAttnUpBlock2D", "UpBlock2D"))
    vae = AutoencoderKL(block_out_channels=(32, 32, 32, 32), latent_channels=4, norm_num_groups=8,
        down_block_types=("DownEncoderBlock2D",) * 4, up_block_types=("UpDecoderBlock2D",) * 4,
        sample_size=512, scaling_factor=0.18215)
    pipe = StableDiffusionPipeline(vae=vae, text_encoder=text_encoder, tokenizer=tokenizer, unet=unet,
        scheduler=PNDMScheduler(steps_offset=1, skip_prk_steps=True), safety_checker=None,
        feature_extractor=None, requires_safety_checker=False)
    pipe.save_pretrained(str(folder), safe_serialization=True)
    (folder / "LICENSE").write_text("Synthetic random-weight fixture generated by Konverter; MIT license.\n")
    print(f"Created synthetic SD1 fixture: {folder}")


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("output", type=Path)
    create_fixture(p.parse_args().output.resolve())
